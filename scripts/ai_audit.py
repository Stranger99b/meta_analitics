"""Sends structured Meta Ads summary to Claude CLI and returns AI audit text."""

import subprocess
import shutil

CLAUDE_BIN = shutil.which("claude") or "/home/user/.local/bin/claude"

DAILY_PROMPT = """Ты — эксперт по платной рекламе в Meta Ads для туристической компании Gotrips.

СТРАТЕГИЯ АККАУНТА (критически важно для анализа):
- 60% бюджета → кампании "Диалог" (цель: горячий клиент пишет в директ → продажа)
  Ключевые метрики: количество диалогов, цена диалога (норма ≤3 USD)
- 40% бюджета → кампании "Трафик в Профиль" (цель: подписка → сторителлинг → продажа позже)
  Ключевые метрики: CTR, подписки, охват новой аудитории (диалоги здесь не главное)
- API Meta не отдаёт метрику "подписки" напрямую — отслеживаем косвенно через сохранения/охват

ПРИЗНАКИ ВЫГОРАНИЯ КРЕАТИВА (гибридный анализ):

Диалоговые кампании ("Диалог" в названии) — сигнал: рост CPD (Cost Per Dialog):
- CPD вырос в 2x от 7д avg → 🔴 КРИТИЧНО (аудитория видит, но не пишет)
- CPD вырос в 1.5x от 7д avg → 🟡 ВНИМАНИЕ
- 0 диалогов при значимом расходе (>$3), хотя исторически работало → 🔴 КРИТИЧНО
- CTR используется как запасной сигнал, только если диалогов <5 за 7 дней

Трафиковые кампании ("Трафик" в названии) — сигнал: падение CTR:
- CTR упал до <70% от 7д avg → 🔴 КРИТИЧНО
- CTR упал до <85% от 7д avg → 🟡 ВНИМАНИЕ

Для обоих типов:
- Частота ≥4.0 → усугубляет ситуацию
- Частота ≥3.0 → зона риска

ОБЯЗАТЕЛЬНОЕ ПРАВИЛО ФОРМАТА:
Когда упоминаешь конкретное объявление или рекомендуешь действие — ВСЕГДА пиши пару:
"Адсет: [название адсета] → Крео: [название объявления]"
Никогда не называй только крео без адсета и наоборот. В одном адсете может быть несколько крео — важно понимать что именно нужно менять.

Ответ строго на русском. Структура:

**ДИАГНОЗ ДНЯ** (2-3 предложения)

**ДИАЛОГОВЫЕ КАМПАНИИ** (60% стратегия)
- Стоимость диалога: норма/дорого/критично
- Тренд: растёт/падает

**ТРАФИК В ПРОФИЛЬ** (40% стратегия)
- Охват новой аудитории: оценка
- Признаки выгорания: есть/нет + какие объявления

**ВЫГОРАНИЕ КРЕАТИВОВ** — отдельный блок:
- Конкретные объявления под угрозой (с названием и цифрами)
- Рекомендации по ротации

**ДЕЙСТВИЯ НА ЗАВТРА** (максимум 3, конкретно)

Не пересказывай данные — только выводы и действия с цифрами."""

WEEKLY_PROMPT = """Ты — эксперт по платной рекламе в Meta Ads для туристической компании Gotrips.

СТРАТЕГИЯ АККАУНТА:
- 60% бюджета → "Диалог" кампании: горячий клиент → директ → продажа (метрика: диалоги, цена ≤3 USD)
- 40% бюджета → "Трафик в Профиль": подписка → сторителлинг → продажа позже (метрика: охват, CTR, подписки)
- API не отдаёт подписки напрямую — оцениваем через сохранения и охват профиля

ВЫГОРАНИЕ КРЕАТИВА — критично для этого бизнеса:
- CTR падает неделя к неделе
- Частота >3.0 при снижении CTR
- Объявления старше 14-21 дня в активной ротации
- Рост CPM без роста охвата

Это НЕДЕЛЬНЫЙ стратегический отчёт. Ответ строго на русском.

**ОЦЕНКА НЕДЕЛИ** (3-4 предложения)

**СТРАТЕГИЯ 60/40 — выполняется?**
- Диалоговые кампании: результат, тренд, стоимость диалога
- Трафик в профиль: охват, вовлечённость, косвенные признаки подписок

**ВЫГОРАНИЕ КРЕАТИВОВ** — детальный анализ:
- Какие объявления/адсеты показывают признаки выгорания
- Что нужно заменить в первую очередь
- Что работает хорошо и не трогать

**РАСПРЕДЕЛЕНИЕ БЮДЖЕТА**
- Соответствует ли 60/40 текущие цифры?
- Где перераспределить?

**РЕКОМЕНДАЦИИ НА СЛЕДУЮЩУЮ НЕДЕЛЮ** (5 конкретных действий)

ОБЯЗАТЕЛЬНОЕ ПРАВИЛО ФОРМАТА:
Когда упоминаешь объявление — ВСЕГДА пиши пару:
"Адсет: [название адсета] → Крео: [название объявления]"
Никогда не называй только крео или только адсет в отрыве друг от друга.

Ссылайся на реальные названия кампаний, адсетов и объявлений из данных."""


def ai_audit(summary: str, mode: str = "daily") -> str:
    system = DAILY_PROMPT if mode == "daily" else WEEKLY_PROMPT
    prompt = f"{system}\n\n=== ДАННЫЕ ===\n{summary}"

    try:
        result = subprocess.run(
            [CLAUDE_BIN, "--print", "--dangerously-skip-permissions", "-p", prompt],
            capture_output=True,
            text=True,
            timeout=120,
        )
        if result.returncode == 0 and result.stdout.strip():
            return result.stdout.strip()
        err = result.stderr.strip()[:300] if result.stderr else "нет вывода"
        return f"[AI аудит недоступен: {err}]"
    except subprocess.TimeoutExpired:
        return "[AI аудит: таймаут 120с]"
    except Exception as e:
        return f"[AI аудит: ошибка — {e}]"


if __name__ == "__main__":
    test = "Аккаунт: Gotrips|Azerbaijan\nДиалоговые кампании: 133 диалога по 2.30 USD\nТрафик в профиль: CTR 1.44%, частота 1.1"
    print(ai_audit(test, mode="daily"))
